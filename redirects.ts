import type { NextConfig } from 'next'
import legacyRedirects from './src/data/legacy-redirects.json'
import { NEW_PATH_BY_LEGACY } from './src/data/legacyUrlMap'

export const redirects: NextConfig['redirects'] = async () => {
  const internetExplorerRedirect = {
    destination: '/ie-incompatible.html',
    has: [
      {
        type: 'header' as const,
        key: 'user-agent',
        value: '(.*Trident.*)', // all ie browsers
      },
    ],
    permanent: false,
    source: '/:path((?!ie-incompatible.html$).*)', // all pages except the incompatibility page
  }

  // 301 redirects from the old falishamanpower.com (WordPress) URLs to their new
  // pages, so Google rankings and old inbound links survive the domain cutover.
  // Generated by scripts/gen_legacy_redirects.py -> src/data/legacy-redirects.json.
  // Keep 301s only for URLs we are NOT serving at their old address. The 1:1
  // country/post/industry pages whose old URL is preserved (see src/data/legacyUrlMap.ts
  // → rewrites.ts) are filtered out here, so their old URL renders the page instead
  // of redirecting. Merged/moved URLs, hub redirects and consolidations (England +
  // Scotland → the UK page) still 301.
  const legacy = (legacyRedirects as { source: string; destination: string }[])
    .filter((r) => !(r.source in NEW_PATH_BY_LEGACY))
    .map((r) => ({
      source: r.source,
      // A handful of imported posts had percent-encoded emoji/Arabic in the old URL;
      // the real post slug has the '%' stripped, so normalise the destination here so
      // these old URLs 301 to the live post instead of a 404. No-op for every other
      // destination (none contain '%').
      destination: r.destination.replace(/%/g, ''),
      // Classic 301 (vs. Next's default 308 for `permanent: true`) — explicitly what
      // the migration playbook asks for; SEO-equivalent but the expected status code.
      statusCode: 301 as const,
    }))

  // England & Scotland share the UK's immigration system — consolidate the
  // near-duplicate regional pages into the single United Kingdom page (avoids
  // Google's "substantially similar regional landing pages" spam signal).
  const countryConsolidation = [
    { source: '/countries/england', destination: '/countries/united-kingdom', statusCode: 301 as const },
    { source: '/countries/scotland', destination: '/countries/united-kingdom', statusCode: 301 as const },
  ]

  return [internetExplorerRedirect, ...countryConsolidation, ...legacy]
}
